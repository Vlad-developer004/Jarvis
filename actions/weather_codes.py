def _wttr_desc(code: int, lang: str) -> tuple[str, str, str]:
    """Return (description, icon, color) for a WWO weather code."""
    entry = _WTTR_CODE_MAP.get(code)
    if entry:
        desc = entry[0] if lang != 'uk' else entry[1]
        return desc, entry[2], entry[3]
    return ('—', '?', '#ffffff')

