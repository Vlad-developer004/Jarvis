def weather_cards(uk: bool) -> list[dict]:
    out = []
    for cid, kind, ru, ukr, phrase in _CARDS:
        name, desc, phrases = ukr if uk else ru
        runnable = kind is not None
        out.append({'id': cid, 'name': name, 'desc': desc, 'cat': 'assistant', 'phrases': phrases, 'mode': 'run' if runnable else 'voice',
                    'try': phrase if runnable else None, 'cmd': 'weather'})
    return out
