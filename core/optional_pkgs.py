"""Optional Python packages that are not shipped in the installer and are fetched the first time a feature needs them.

`ensure('gemini')` returns True when the package set is importable: already bundled or installed (a source checkout), downloaded earlier, or downloaded now.
The wheels are listed with their URL and SHA-256 in data/optional_packages.json (generated by tools/make_optional_manifest.py), HTTPS only, each file is
checked against its pin before anything is unpacked, and the archives go through the same traversal-safe extractor as the models. The packages land in
<app data>/packages/<feature>/ and are appended to sys.path, so a bundled copy always wins over a downloaded one."""
from __future__ import annotations

import importlib.util
import json
import os
import shutil
import sys
import threading
import zipfile
from pathlib import Path

from core.logging_setup import get_logger
from core.safe import swallow as _swallow

_log = get_logger('optional_pkgs')
_MANIFEST = 'optional_packages.json'
_lock = threading.Lock()
_ready: set[str] = set()
_failed: dict[str, float] = {}
_RETRY_AFTER = 120.0          # seconds before a failed download is tried again
_ATTEMPTS = 3                 # tries per file inside one download


def _manifest() -> dict:
    """The pinned wheel list."""
    from core.download import bundled_data_file
    return json.loads(bundled_data_file(_MANIFEST).read_text(encoding='utf-8'))


def packages_dir() -> Path:
    from config_pack.config import get_app_data_root
    return Path(get_app_data_root()) / 'packages'


def _importable(module: str) -> bool:
    try:
        return importlib.util.find_spec(module) is not None
    except (ImportError, ValueError):
        return False


def _activate(target: Path) -> None:
    """Makes the unpacked packages importable; native libraries next to them are found through their own folders."""
    path = str(target)
    if path not in sys.path:
        sys.path.append(path)
    importlib.invalidate_caches()
    if hasattr(os, 'add_dll_directory'):
        for sub in {p.parent for p in target.rglob('*.dll')}:
            try:
                os.add_dll_directory(str(sub))
            except OSError:
                pass


def _notify(feature: str, active: bool, failed: bool = False) -> None:
    """Best-effort window notice around a download; never raises."""
    try:
        from ui_next import host as _hud
        key = f'pkg_{feature}'
        if failed:
            _hud.notify(key, f'Не удалось скачать компонент «{feature}» — проверьте интернет', _hud.RED, duration=6000)
        elif active:
            _hud.notify(key, f'Скачиваю компонент «{feature}» (один раз)...', _hud.AMBER)
        else:
            _hud.clear_notify(key)
    except Exception:
        _swallow()


def _download(feature: str, spec: dict, target: Path) -> None:
    import requests
    from core.download import require_https, safe_extract_zip, sha256_file
    tmp_root = target.with_name(target.name + '.part')
    shutil.rmtree(tmp_root, ignore_errors=True)
    tmp_root.mkdir(parents=True)
    try:
        for wheel in spec['wheels']:
            dest = tmp_root / wheel['file']
            for attempt in range(_ATTEMPTS):                 # a stalled connection is common on a weak network: start the file over
                try:
                    with requests.get(require_https(wheel['url']), stream=True, timeout=(10, 30)) as r:
                        r.raise_for_status()
                        with open(dest, 'wb') as f:
                            for chunk in r.iter_content(1 << 20):
                                f.write(chunk)
                    break
                except (requests.ConnectionError, requests.Timeout, requests.exceptions.ChunkedEncodingError) as ex:
                    if attempt == _ATTEMPTS - 1:
                        raise
                    _log.info('%s: %s, trying again', wheel['file'], type(ex).__name__)
            if sha256_file(dest) != wheel['sha256'].lower():
                raise ValueError(f"checksum mismatch for {wheel['file']}")
            with zipfile.ZipFile(dest) as zf:
                safe_extract_zip(zf, tmp_root / 'site')
            dest.unlink()
        (tmp_root / 'site' / '.complete').write_text(feature, encoding='utf-8')
        shutil.rmtree(target, ignore_errors=True)
        os.replace(tmp_root / 'site', target)
    finally:
        shutil.rmtree(tmp_root, ignore_errors=True)


def ensure(feature: str) -> bool:
    """True when the packages of `feature` can be imported now. Blocks while a download runs; a failed one is not retried for two minutes."""
    import time
    if feature in _ready:
        return True
    with _lock:
        if feature in _ready:
            return True
        try:
            spec = _manifest()[feature]
        except (OSError, ValueError, KeyError) as ex:
            _log.warning('no optional package set %r: %s', feature, ex)
            return False
        if _importable(spec['import']):
            _ready.add(feature)
            return True
        target = packages_dir() / feature
        if not (target / '.complete').is_file():
            if time.time() - _failed.get(feature, 0.0) < _RETRY_AFTER:
                return False
            _notify(feature, active=True)
            try:
                _download(feature, spec, target)
            except Exception as ex:
                _log.warning('download of %r failed: %s', feature, ex)
                _failed[feature] = time.time()
                _notify(feature, active=False, failed=True)
                return False
            _notify(feature, active=False)
            _log.info('optional package set %r installed in %s', feature, target)
        _activate(target)
        ok = _importable(spec['import'])
        if ok:
            _ready.add(feature)
        else:
            _log.warning('%r is unpacked but %s does not import', feature, spec['import'])
        return ok
