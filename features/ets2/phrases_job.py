def _wear_phrase(component: str, pct: int) -> str:
    ru_name = _WEAR_NAMES_RU_STRESSED.get(component, component)
    uk_name = _WEAR_NAMES_UK_STRESSED.get(component, component)
    
    fem_ru = component in ('коробка передач', 'кабина')
    neu_ru = component == 'шасси'
    pl_ru  = component == 'колёса'
    
    uk_base_name = _WEAR_NAMES_UK.get(component, component)
    fem_uk = uk_base_name in ('коробка передач', 'кабіна')
    neu_uk = uk_base_name == 'шасі'
    pl_uk  = uk_base_name == 'колеса'

    ru_end = 'а' if fem_ru else 'о' if neu_ru else 'ы' if pl_ru else ''

    def _ukform(base: str) -> str:
        if fem_uk: return f"{base}а"
        if neu_uk: return f"{base}е"
        if pl_uk:  return f"{base}і"
        return f"{base}ий"

    p = _pct_str(pct)

    if pct >= 90:
        return _r(
            [f"Сэр, крит+ический изн+ос! {ru_name.capitalize()} изн+ошен{ru_end} на {p}. Ср+очно в с+ервис."],
            [f"Сер, крит+ичне зн+ошення! {uk_name.capitalize()} {_ukform('зн+ошен')} на {p}. Терм+іново до с+ервісу."]
        )
    if pct >= 75:
        return _r(
            [f"Сэр, с+ильный изн+ос. {ru_name.capitalize()} изн+ошен{ru_end} на {p}. Рекоменд+ую посет+ить с+ервис."],
            [f"Сер, с+ильне зн+ошення. {uk_name.capitalize()} {_ukform('зн+ошен')} на {p}. Рекоменд+ую відв+ідати с+ервіс."]
        )
    if pct >= 50:
        return _r(
            [f"Сэр, {ru_name} изн+ошен{ru_end} на {p}. Ст+оит заплан+ировать техообсл+уживание."],
            [f"Сер, {uk_name} {_ukform('зн+ошен')} на {p}. В+арто заплан+увати техобсл+уговування."]
        )
    return _r(
        [f"Сэр, {ru_name} изн+ошен{ru_end} на {p}. Рекоменд+ую заглян+уть в с+ервис п+осле р+ейса."],
        [f"Сер, {uk_name} {_ukform('зн+ошен')} на {p}. Рекоменд+ую заглян+ути до с+ервісу п+ісля р+ейсу."]
    )


