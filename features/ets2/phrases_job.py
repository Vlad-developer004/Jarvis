"""Job-lifecycle narration: job pickup/delivery announcements and the
end-of-job wear report. Split out of the old phrases.py purely for file
size; no behavior change.
"""
from .phrases_common import (
    _fmt_km, _fmt_euro, _fmt_xp, _resolve_addr, _addr, _r, _pct_str,
    _WEAR_NAMES_UK, _WEAR_NAMES_RU_STRESSED, _WEAR_NAMES_UK_STRESSED,
)

def announce_job_start(data: dict) -> str:
    """Return TTS text for job start announcement (fallback, no LLM)."""
    cargo = str(data.get("cargo", "")).strip()
    if not cargo:
        return ""
    mass_kg = float(data.get("cargoMass", 0))
    mass_t = mass_kg / 1000.0 if mass_kg >= 500 else None
    city_src = str(data.get("citySrc", "")).strip()
    city_dst = str(data.get("cityDst", "")).strip()
    comp_src = str(data.get("compSrc", "")).strip()
    comp_dst = str(data.get("compDst", "")).strip()
    income = int(data.get("jobIncome", 0))
    planned_km = int(data.get("plannedDistanceKm", 0))
    special = bool(data.get("specialJob", False))
    route_time_s = float(data.get("routeTime", 0))
    hour = (int(data.get("time_abs", 0)) % 1440) // 60

    from_str = f"{comp_src}, {city_src}" if comp_src else city_src
    to_str   = f"{comp_dst}, {city_dst}" if comp_dst else city_dst
    mass_str = f"{int(round(mass_t))} тонн " if mass_t else ""

    line = _r(
        [f"Груз пр+инят, сэр. Вез+ём {mass_str}{cargo}" + (f" из {from_str}" if from_str else "") + (f" в {to_str}." if to_str else ".")],
        [f"Вант+аж прийн+ято, сер. Вез+емо {mass_str}{cargo}" + (f" з {from_str}" if from_str else "") + (f" до {to_str}." if to_str else ".")]
    )
    parts = [line]

    cargo_lower = cargo.lower()
    cargo_desc_ru = ""
    cargo_desc_uk = ""
    if any(k in cargo_lower for k in ("medical", "лекарств", "вакцин", "аппарат", "электрон", "компьют", "стекл", "fragile", "хрупк", "техник", "телевиз", "прибор")):
        cargo_desc_ru = "Груз хр+упкий и дорогостоящий, сэр. Едем аккуратней, избег+аем р+езких тормож+ений и нер+овностей."
        cargo_desc_uk = "Вант+аж крихк+ий та дорог+ий, сер. Їдемо обер+ежніше, уник+аємо р+ізких гальмув+ань та нер+івностей."
    elif any(k in cargo_lower for k in ("кислот", "бензин", "топлив", "газ", "хими", "acid", "gas", "chem", "fuel", "flamm", "взрыв", "опасн")):
        cargo_desc_ru = "Вез+ём оп+асный груз, сэр. Соблюд+аем дист+анцию и скоростн+ой реж+им, с х+имией ш+утки плох+и."
        cargo_desc_uk = "Вез+емо небезпечний вант+аж, сер. Дотр+имуємось дист+анції та швидк+існого реж+иму, з х+імією ж+арти пог+ані."
    elif any(k in cargo_lower for k in ("food", "молок", "мясо", "фрукт", "рыба", "рефриж", "milk", "meat", "fish", "fruit", "продукт", "еда")):
        cargo_desc_ru = "Скороп+ортящийся тов+ар. В+ажно достав+ить ег+о в+овремя, пок+а держится температурный реж+им."
        cargo_desc_uk = "Вант+аж шв+идко пс+ується. В+ажливо дост+авити йог+о вч+асно, пок+и трим+ається температурний реж+им."
    elif any(k in cargo_lower for k in ("машин", "трактор", "экскаватор", "автомоб", "car", "truck", "tractor", "excavator", "оборудов", "яхт")):
        cargo_desc_ru = "Крупногабар+итная т+ехника на платф+орме. След+им за высот+ой под мост+ами и р+адиусом повор+ота."
        cargo_desc_uk = "Великогабар+итна т+ехніка на платф+ормі. Стеж+имо за висот+ою під мост+ами та р+адіусом повор+оту."
