        cargo_desc_ru = "Сып+учий груз. На ух+абах м+ожет смещ+аться ц+ентр т+яжести, держ+им пл+авный ход."
        cargo_desc_uk = "Сип+учий вант+аж. На виб+оїнах м+оже зміщ+уватись ц+ентр ваг+и, трим+аємо пл+авний хід."
