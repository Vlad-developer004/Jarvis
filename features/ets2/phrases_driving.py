def event_eta(route_hours: float) -> str:
    a = _addr()
    if route_hours < 0.75:
        return _r(
            [
                f"До прибытия меньше часа, {a}.",
                f"Почти добрались, {a}. Меньше часа осталось.",
                f"{a}, финальный отрезок — менее часа езды.",
            ],
            [
                f"До прибуття менше години, {a}.",
                f"Майже добрались, {a}. Менше години залишилось.",
                f"{a}, фінальний відрізок — менше години їзди.",
            ]
        )
    if route_hours < 1.5:
        return _r(
            [
                f"До прибытия около часа, {a}.",
                f"{a}, осталось примерно час езды.",
                f"Час пути впереди, {a}. Держите темп.",
            ],
            [
                f"До прибуття близько години, {a}.",
                f"{a}, залишилось приблизно година їзди.",
                f"Година шляху попереду, {a}. Тримайте темп.",
            ]
        )
    h = int(round(route_hours))
    h_ru = f"{h} {_decline_ru(h, 'час', 'часа', 'часов')}"
    h_uk = f"{h} {_decline_uk(h, 'година', 'години', 'годин')}"
    return _r(
        [
            f"До прибытия ещё {h_ru}, {a}.",
            f"{a}, {h_ru} впереди. Планируйте заправку и отдых.",
            f"Осталось примерно {h_ru} езды, {a}. Не торопитесь.",
        ],
        [
            f"До прибуття ще {h_uk}, {a}.",
            f"{a}, {h_uk} попереду. Плануйте заправку та відпочинок.",
            f"Залишилось приблизно {h_uk} їзди, {a}. Не поспішайте.",
        ]
    )


