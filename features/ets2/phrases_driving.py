def event_engine_off(p_brake: bool, lights_on: bool) -> str:
    a = _addr()
    if not p_brake and lights_on:
        return _r(
            [
                f"{a}, двигатель заглушен. Ручник не поднят и фары ещё горят — не забудьте.",
                f"Двигатель выключен, {a}. Напоминаю: ручник опущен и фары включены.",
            ],
            [
                f"{a}, двигун заглушено. Ручник не піднятий і фари ще горять — не забудьте.",
                f"Двигун вимкнено, {a}. Нагадую: ручник опущений і фари увімкнені.",
            ]
        )
    if not p_brake:
        return _r(
            [
                f"{a}, двигатель заглушен. Ручник не поднят — придержите машину.",
                f"Двигатель выключен. {a}, поднимите ручник.",
                f"Стоп, {a}. Двигатель заглушен, но ручник не поднят.",
            ],
            [
                f"{a}, двигун заглушено. Ручник не піднятий — притримайте машину.",
                f"Двигун вимкнено. {a}, підніміть ручник.",
                f"Стоп, {a}. Двигун заглушено, але ручник не піднятий.",
            ]
        )
    if lights_on:
        return _r(
            [
                f"Двигатель заглушен, {a}. Фары ещё включены — не забудьте выключить.",
                f"Стоп, {a}. Ручник поднят, но фары горят. Выключите свет.",
            ],
            [
                f"Двигун заглушено, {a}. Фари ще увімкнені — не забудьте вимкнути.",
                f"Стоп, {a}. Ручник піднятий, але фари горять. Вимкніть світло.",
            ]
        )
    return _r(
        [
            f"Двигатель заглушен. Ручник поднят, фары выключены — всё в порядке, {a}.",
            f"Стоп. Ручник поднят, свет выключен. Хорошая остановка, {a}.",
            f"Машина припаркована правильно. Отдыхайте, {a}.",
            f"Всё чисто, {a}. Двигатель заглушен, стоянка оформлена по правилам.",
        ],
        [
            f"Двигун заглушено. Ручник піднятий, фари вимкнені — всё гаразд, {a}.",
            f"Стоп. Ручник піднятий, світло вимкнено. Гарна зупинка, {a}.",
            f"Машину припарковано правильно. Відпочивайте, {a}.",
            f"Всё чисто, {a}. Двигун заглушено, стоянка оформлена за правилами.",
        ]
    )


